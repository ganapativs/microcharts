/**
 * Emit `src/lib/charts/preview-live.generated.ts` — a per-slug map of LAZY
 * dynamic imports for each chart's interactive `PreviewLive`. The gallery's
 * client stage (`gallery-stage.tsx`) reads this map so its INITIAL client graph
 * carries zero interactive/motion chart code: static previews render on the
 * server, and each live preview streams in as its own chunk after mount.
 *
 * Every entry is a distinct `import("./<slug>.live")` string literal so Turbopack
 * code-splits one chunk per chart (an expression import would collapse them into
 * a single context module). Only slugs with a `<slug>.live.tsx` half appear —
 * the rest simply stay static (`wind-barb` ships no interactive entry at all).
 *
 * Slugs are read from the `.live.tsx` files on disk rather than by loading the
 * registry: `registry.ts` now imports the STATIC halves (that is the whole point
 * of the split — see `ChartModuleStatic`), so it no longer carries `PreviewLive`
 * to detect.
 *
 * A Vitest guard (`preview-live-generated.test.ts`) fails if this map drifts
 * from the live registry, so a new chart can't silently miss its live upgrade.
 * Regenerate with `pnpm gen:preview-live`.
 *
 * WHY esbuild (this was a `tsx` script): the registry is TSX, and `tsx` was never
 * declared in any package.json — `pnpm gen:preview-live` simply failed, so this
 * snapshot had no working regeneration path. Node's native type-stripping can't
 * load it either (it does not handle JSX). esbuild is already a root dependency
 * and `scripts/figma-export/lib/registry.mjs` loads this same registry the same
 * way, so this adds NO dependency. Matches `gen-entries.mjs`.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = join(here, "..");
const chartsDir = join(docsDir, "src", "lib", "charts");

{
  const slugs = readdirSync(chartsDir)
    .filter((f) => f.endsWith(".live.tsx"))
    .map((f) => f.replace(/\.live\.tsx$/, ""))
    .sort();

  const lines = slugs
    .map(
      (slug) =>
        `  ${JSON.stringify(slug)}: () => import(${JSON.stringify(`./${slug}.live`)}).then((m) => ({ default: m.PreviewLive! })),`,
    )
    .join("\n");

  const body = `/* GENERATED by scripts/gen-preview-live.mjs — do not edit. Run \`pnpm gen:preview-live\`. */
import type { ComponentType } from "react";

/** Lazy per-slug interactive preview loaders. Each entry is a distinct dynamic
 *  import so the gallery's initial client graph carries zero interactive/motion
 *  chart code; live previews stream in per-chart after mount. Only slugs whose
 *  module exports a \`PreviewLive\` appear here. */
export const PREVIEW_LIVE: Record<string, () => Promise<{ default: ComponentType }>> = {
${lines}
};
`;

  const out = join(docsDir, "src", "lib", "charts", "preview-live.generated.ts");
  writeFileSync(out, body);
  // Normalize to oxfmt (unquoted keys, line wrapping) so the committed snapshot
  // stays clean under `format:check` no matter how this template is spaced.
  // Via `pnpm exec` — bare `oxfmt` is not on PATH.
  execFileSync("pnpm", ["exec", "oxfmt", out], { cwd: docsDir, stdio: "ignore" });
  console.log(`gen-preview-live: wrote ${slugs.length} lazy preview loaders to ${out}`);
}
