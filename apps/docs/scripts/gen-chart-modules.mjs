/**
 * Emit `src/lib/charts/modules.generated.ts` — a per-slug map of LAZY dynamic
 * imports for each chart's full `ChartModule` (entry + Preview + Mark + knobs +
 * code strings).
 *
 * WHY: `lib/charts/registry.ts` statically imports all 106 modules, and every
 * module imports its chart's STATIC **and** INTERACTIVE entry. Any `'use client'`
 * file that touches the registry therefore drags the whole ~311 kB-gzip chart
 * graph into that route's client bundle — measured, not estimated. The chart doc
 * pages only ever need ONE slug, so they resolve it through this map instead and
 * pay for one chart (~6 kB gzip) rather than a hundred and six.
 *
 * Every entry is a distinct `import("./<slug>")` string literal so Turbopack
 * code-splits one chunk per chart (an expression import would collapse them all
 * into a single context module — the exact bug this file exists to avoid).
 *
 * Slugs come from `entries.generated.json` (the data-only snapshot), so this
 * script needs no bundler and no React. `modules-generated.test.ts` fails if the
 * map drifts from the registry. Regenerate with `pnpm gen:chart-modules`.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = join(here, "..");
const chartsDir = join(docsDir, "src", "lib", "charts");

const entries = JSON.parse(readFileSync(join(chartsDir, "entries.generated.json"), "utf8"));
const slugs = entries.map((e) => e.slug).sort();

// `<slug>.live` where it exists, else the static module. The live half is the
// ONLY module that imports a chart's `…/interactive` ('use client') entry, so
// resolving it through a dynamic import keeps those twins in async chunks
// instead of a route's eager client-reference graph. `wind-barb` ships no
// interactive entry, so it has no live half.
const hasLive = (slug) => existsSync(join(chartsDir, `${slug}.live.tsx`));
const lines = slugs
  .map(
    (slug) =>
      `  ${JSON.stringify(slug)}: () => import(${JSON.stringify(`./${slug}${hasLive(slug) ? ".live" : ""}`)}),`,
  )
  .join("\n");

const body = `/* GENERATED by scripts/gen-chart-modules.mjs — do not edit. Run \`pnpm gen:chart-modules\`. */
import type { ChartModule } from "./types";

/** Lazy per-slug \`ChartModule\` loaders. Each entry is a distinct dynamic import,
 *  so a route that renders ONE chart downloads one chart's chunk instead of the
 *  whole 106-chart registry graph. Use this from every \`'use client'\` file that
 *  needs a module by slug; \`./registry\` is for the server only. */
export const CHART_MODULE_LAZY: Record<
  string,
  () => Promise<{ default: ChartModule }>
> = {
${lines}
};
`;

const out = join(chartsDir, "modules.generated.ts");
// Normalize to oxfmt so the committed snapshot stays clean under `format:check`.
// Over STDIN: `.oxfmtrc.json` ignores `**/*.generated.ts`, so oxfmt given the
// written path finds zero targets and exits 2. Same workaround as gen-entries.
const formatted = execFileSync("pnpm", ["exec", "oxfmt", "--stdin-filepath=modules.ts"], {
  cwd: docsDir,
  input: body,
  encoding: "utf8",
});
writeFileSync(out, formatted);
console.log(`gen-chart-modules: wrote ${slugs.length} lazy module loaders to ${out}`);
