/**
 * Emit `playground-caps.generated.ts` — which playground axes actually change markup.
 * Renders each spec from `dist/`, records only real effects; thrown fixtures surface bugs.
 * Regenerate: `pnpm gen:playground-caps` (guarded by `playground-caps.test.ts`).
 */
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = join(here, "..");
const out = join(docsDir, "src", "lib", "charts", "playground-caps.generated.ts");

const res = await build({
  stdin: {
    contents: `
      export { CHART_MODULES } from "./src/lib/charts/registry.ts";
      export { injectChartProps } from "./src/lib/charts/inject-chart-props.ts";
      export { FIXTURES, PLAIN_SERIES, applyFixture } from "./src/components/charts/playground-options.ts";
    `,
    resolveDir: docsDir,
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  platform: "node",
  jsx: "automatic",
  external: ["react", "react-dom", "react/jsx-runtime", "react-dom/server"],
  write: false,
  logLevel: "silent",
});

const tmp = join(docsDir, ".gen-playground-caps-bundle.mjs");
writeFileSync(tmp, res.outputFiles[0].text);

try {
  const { renderToStaticMarkup } = await import("react-dom/server");
  const mod = await import(`${new URL(`file://${tmp}`).href}?t=${res.outputFiles[0].hash}`);
  const { CHART_MODULES, injectChartProps, FIXTURES, PLAIN_SERIES, applyFixture } = mod;

  const CURRENCY = { style: "currency", currency: "EUR", maximumFractionDigits: 0 };
  const caps = {};
  const notes = [];

  for (const [slug, m] of Object.entries(CHART_MODULES).sort(([a], [b]) => a.localeCompare(b))) {
    const spec = m.playground;
    const entry = m.entry;
    if (!spec) continue;
    const state = Object.fromEntries((spec.knobs ?? []).map((k) => [k.key, k.init]));
    const data = spec.data ?? [];

    const paint = (series, props) => {
      const node = spec.render(state, series);
      return renderToStaticMarkup(props ? injectChartProps(node, props) : node);
    };

    let base;
    try {
      base = paint(data);
    } catch (e) {
      notes.push(`${slug}: base render threw — ${String(e.message ?? e).slice(0, 80)}`);
      caps[slug] = {
        fixtures: [],
        format: false,
        locale: false,
        title: false,
        summary: false,
        idNaming: false,
      };
      continue;
    }

    // Threaded through `render` when the spec takes a series; cloned as a `data`
    // prop when the spec hard-codes one AND the chart's data is a plain series.
    const threads = !!spec.data;
    const injects = !threads && PLAIN_SERIES.test(entry.dataShape) && entry.demo?.length > 0;
    const source = threads ? data : (entry.demo ?? []);
    const fixtures = [];
    if (threads || injects) {
      for (const f of FIXTURES) {
        if (f.key === "typical") continue;
        const series = applyFixture(f.key, source);
        try {
          const html = threads ? paint(series) : paint(data, { data: series });
          if (html !== base) fixtures.push(f.key);
        } catch (e) {
          notes.push(`${slug}: fixture "${f.key}" threw — ${String(e.message ?? e).slice(0, 80)}`);
        }
      }
    }

    const safe = (props) => {
      try {
        return paint(data, props);
      } catch {
        return base;
      }
    };
    const formatted = safe({ format: CURRENCY });
    const localised = safe({ format: CURRENCY, locale: "de-DE" });

    // Probe output, not diff vs base — most specs use `summary={false}`; reset to
    // named state first, same as the playground "auto" knob.
    const named = { summary: undefined };
    const titled = safe({ ...named, title: "Probe title 4711" });
    const described = safe({ summary: "Probe summary 4711" });
    const muted = safe({ ...named, summary: false });
    const identified = safe({ ...named, title: "Probe title 4711", id: "probe-id-4711" });

    caps[slug] = {
      fixtures,
      format: formatted !== base,
      locale: localised !== formatted,
      title: titled.includes("Probe title 4711"),
      summary:
        described.includes("Probe summary 4711") ||
        (/aria-hidden="true"/.test(muted) && !/aria-hidden="true"/.test(titled)),
      idNaming: identified.includes('aria-labelledby="probe-id-4711'),
    };
  }

  const body = `/* GENERATED by scripts/gen-playground-caps.mjs — do not edit. Run \`pnpm gen:playground-caps\`. */

export interface PlaygroundCaps {
  fixtures: string[];
  format: boolean;
  locale: boolean;
  title: boolean;
  summary: boolean;
  idNaming: boolean;
}

export const PLAYGROUND_CAPS: Record<string, PlaygroundCaps> = ${JSON.stringify(caps, null, 2)};
`;

  const formatted = execFileSync("pnpm", ["exec", "oxfmt", "--stdin-filepath=caps.ts"], {
    cwd: docsDir,
    input: body,
    encoding: "utf8",
  });
  writeFileSync(out, formatted);

  const n = Object.keys(caps).length;
  const withFixtures = Object.values(caps).filter((c) => c.fixtures.length).length;
  const withFormat = Object.values(caps).filter((c) => c.format).length;
  const withLocale = Object.values(caps).filter((c) => c.locale).length;
  const withTitle = Object.values(caps).filter((c) => c.title).length;
  console.log(
    `gen-playground-caps: ${n} charts — fixtures ${withFixtures}, format ${withFormat}, locale ${withLocale}, title ${withTitle}`,
  );
  for (const line of notes) console.log(`  ⚠ ${line}`);
} finally {
  rmSync(tmp, { force: true });
}
