/**
 * Emit `src/lib/charts/docs-code.generated.ts` — the copy-pasteable JSX behind
 * `<Playground>`, `<Sizing>` and `<FourContexts>`, as plain strings.
 *
 * WHY a snapshot: `md-transform.ts` turns the docs' MDX into the `.md` mirrors
 * and `/llms-full.txt`, and it runs BOTH in Next (imported from `lib/source.ts`,
 * which every docs route pulls) and in plain Node (`scripts/gen-md.ts`). It can
 * therefore never import `lib/charts/registry` — that would put all 106 chart
 * modules, each with its interactive twin, on the docs routes' graph. So the
 * strings are extracted here, once, and the transform reads the result.
 *
 * WHY esbuild, and why a `.ts` module rather than JSON: same as
 * `gen-entries.mjs` — the registry is TSX, so Node's own type-stripping can't
 * load it, and esbuild is already how this repo reads the registry from a
 * script. The output is `.ts` (not `.json`) because `md-transform.ts` imports it
 * statically and must keep working under Node's native TypeScript, where a JSON
 * import would need an import attribute.
 *
 * A Vitest guard (`docs-code-generated.test.ts`) fails if the checked-in file
 * drifts from the live registry, so it can never go stale.
 */
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = join(here, "..");
const chartsDir = join(docsDir, "src", "lib", "charts");
const out = join(chartsDir, "docs-code.generated.ts");

// The LIVE half of each module is what a chart page actually renders (the
// playground's interactive snippet lives there, and it is the import path the
// page's Code tab shows). `registry.ts` deliberately carries only the static
// halves, and `modules.generated.ts` reaches the live ones through dynamic
// imports — so bundle them statically here instead.
const slugs = readdirSync(chartsDir)
  .filter((f) => f.endsWith(".live.tsx"))
  .map((f) => f.slice(0, -".live.tsx".length))
  .sort();

const res = await build({
  stdin: {
    contents: [
      // `registry` covers all 106 static halves; the live modules then override
      // each one with its interactive twin.
      `import { CHART_MODULES as STATIC_MODULES } from "./src/lib/charts/registry.ts";`,
      ...slugs.map((s, i) => `import m${i} from "./src/lib/charts/${s}.live";`),
      `export const CHART_MODULES = {`,
      `  ...STATIC_MODULES,`,
      ...slugs.map((s, i) => `  ${JSON.stringify(s)}: m${i},`),
      `};`,
      `export { buildDocsCode } from "./src/lib/charts/docs-code.ts";`,
    ].join("\n"),
    resolveDir: docsDir,
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  platform: "node",
  jsx: "automatic",
  external: ["react", "react-dom", "react/jsx-runtime", "react-dom/server"],
  write: false,
  logLevel: "silent",
});

const tmp = join(docsDir, ".gen-docs-code-bundle.mjs");
writeFileSync(tmp, res.outputFiles[0].text);
try {
  const mod = await import(`${new URL(`file://${tmp}`).href}?t=${res.outputFiles[0].hash}`);
  const code = mod.buildDocsCode(mod.CHART_MODULES);
  const header = [
    "// GENERATED by scripts/gen-docs-code.mjs — do not edit.",
    "// Run `pnpm gen:docs-code` after changing a chart's playground, recipes, or",
    "// authored four-homes contexts. See lib/charts/docs-code.ts for the why.",
    'import type { ChartDocsCode } from "./docs-code";',
    "",
    "export const DOCS_CODE: Record<string, ChartDocsCode> =",
  ].join("\n");
  const body = `${JSON.stringify(code, null, 2)};\n`;
  const formatted = execFileSync("pnpm", ["exec", "oxfmt", "--stdin-filepath=docs-code.ts"], {
    cwd: docsDir,
    input: `${header} ${body}`,
    encoding: "utf8",
  });
  writeFileSync(out, formatted);
  console.log(`gen-docs-code: wrote snippets for ${Object.keys(code).length} charts to ${out}`);
} finally {
  rmSync(tmp, { force: true });
}
